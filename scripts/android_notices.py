class Archive:
    """An APK, or an AAB with its module prefix (base/, feature/) removed."""

    def __init__(self, path: str):
        try:
            self.zip = zipfile.ZipFile(path)
        except (OSError, zipfile.BadZipFile) as exc:
            raise InputError(f"cannot open {path}: {exc}") from exc
        names = self.zip.namelist()
        self.is_bundle = "BundleConfig.pb" in names
        self.entries: dict[str, zipfile.ZipInfo] = {}
        for info in self.zip.infolist():
            if info.is_dir():
                continue
            name = info.filename
            if self.is_bundle:
                if "/" not in name:
                    continue
                name = name.split("/", 1)[1]
            self.entries.setdefault(name, info)

    def read(self, name: str) -> bytes:
        return self.zip.read(self.entries[name])

    def size(self, name: str) -> int:
        info = self.entries.get(name)
        return info.file_size if info else -1


def parse_definitions(raw: bytes, origin: str) -> dict | None:
    """AboutLibraries JSON -> {"libraries": [...], "licenses": {...}}, else None."""
    try:
        data = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        return None
    if isinstance(data, dict) and isinstance(data.get("libraries"), list) and isinstance(data.get("licenses"), dict):
        # Tolerate hand-edited files: libraries are objects with string ids, licenses objects.
        libraries = []
        for lib in data["libraries"]:
            if isinstance(lib, dict):
                lib["uniqueId"] = str(lib.get("uniqueId") or lib.get("name") or "?")
                lib["licenses"] = [str(k) for k in (lib.get("licenses") or []) if k]
                libraries.append(lib)
        licenses = {str(k): v if isinstance(v, dict) else {"content": str(v)} for k, v in data["licenses"].items()}
        return {"libraries": libraries, "licenses": licenses, "origin": origin, "format": "aboutlibraries"}
    if isinstance(data, list) and all(isinstance(a, dict) and "groupId" in a and "artifactId" in a for a in data):
        # Licensee's artifacts.json: coordinates and SPDX ids, no texts.
        libraries = []
        for a in data:
            ids = [s.get("identifier") for s in a.get("spdxLicenses", []) if s.get("identifier")]
            ids += [u.get("name") or u.get("url") for u in a.get("unknownLicenses", []) if u.get("name") or u.get("url")]
            libraries.append({
                "uniqueId": f"{a['groupId']}:{a['artifactId']}", "artifactVersion": a.get("version"),
                "name": a.get("name") or a["artifactId"], "licenses": ids,
                "website": (a.get("scm") or {}).get("url"),
            })
        return {"libraries": libraries, "licenses": {}, "origin": origin, "format": "licensee"}
    return None


def load_source(path: str, definitions_entry: str | None = None) -> tuple[dict | None, Archive | None]:
    """Definitions plus the archive they came from (None for a JSON file)."""
    p = Path(path)
    if not p.is_file():
        raise InputError(f"{path}: no such file")
    if p.suffix.lower() == ".json":
        defs = parse_definitions(p.read_bytes(), path)
        if defs is None:
            raise InputError(f"{path}: neither AboutLibraries nor Licensee JSON")
        return defs, None
    archive = Archive(path)
    if definitions_entry:
        if archive.is_bundle and archive.size(definitions_entry) < 0 and "/" in definitions_entry:
            definitions_entry = definitions_entry.split("/", 1)[1]  # base/res/... -> res/...
        if archive.size(definitions_entry) <= 0:
            return None, archive
        return parse_definitions(archive.read(definitions_entry), f"{path}!{definitions_entry}"), archive
    # R8 resource shortening renames res/raw/aboutlibraries.json (e.g. res/M7.json): sniff content.
    candidates = sorted(n for n in archive.entries if n.startswith("res/") and n.endswith(".json"))
    if DEFINITIONS_ENTRY in candidates:
        candidates.remove(DEFINITIONS_ENTRY)
        candidates.insert(0, DEFINITIONS_ENTRY)
    found = []
    for name in candidates:
        if archive.size(name) > 0:
            defs = parse_definitions(archive.read(name), f"{path}!{name}")
            if defs and defs["format"] == "aboutlibraries":
                found.append(defs)
    if len(found) > 1:
        raise InputError(f"{path}: several AboutLibraries files: {[d['origin'] for d in found]}")
    if found:
        return found[0], archive
    if archive.size(LICENSEE_ENTRY) > 0:
        return parse_definitions(archive.read(LICENSEE_ENTRY), f"{path}!{LICENSEE_ENTRY}"), archive
    return None, archive


def license_of(defs: dict, key: str) -> dict:
    return defs["licenses"].get(key) or {}


def family(lic: dict, key: str) -> str:
    return lic.get("spdxId") or key


def body(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not APPENDIX_LINE_RE.search(line))


def has_placeholder(text: str) -> bool:
    return bool(PLACEHOLDER_RE.search(body(text)))


def has_copyright(text: str) -> bool:
    return bool(COPYRIGHT_LINE_RE.search(body(text)))


def norm(text: str) -> str:
    return " ".join(text.split())


