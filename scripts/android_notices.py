def gradle_cache(home: str | None) -> Path:
    base = Path(home or os.environ.get("GRADLE_USER_HOME") or Path.home() / ".gradle")
    return base / "caches" / "modules-2" / "files-2.1"


def artifact_files(group: str, artifact: str, version: str, cache: Path, repos: list[Path]) -> tuple[list[Path], bool]:
    """Runtime .aar/.jar files of a coordinate, and whether its group is known at all."""
    files, known = [], False
    dirs = []
    if (cache / group).is_dir():
        known = True
        dirs += [d for d in (cache / group / artifact / version).glob("*") if d.is_dir()]
    for repo in repos:
        rdir = repo.joinpath(*group.split("."))
        if rdir.is_dir():
            known = True
            if (rdir / artifact / version).is_dir():
                dirs.append(rdir / artifact / version)
    wanted = {f"{artifact}-{version}.aar", f"{artifact}-{version}.jar"} | runtime_file_names(dirs, artifact, version)
    seen = set()
    for d in dirs:
        for p in sorted(d.iterdir()):
            if p.name in wanted and p.name not in seen:  # same file in several cache dirs or repos
                seen.add(p.name)
                files.append(p)
    return files, known


def variants_of(data) -> list[dict]:
    """Gradle module metadata variants, ignoring malformed entries."""
    variants = data.get("variants") if isinstance(data, dict) else None
    return [v for v in variants or [] if isinstance(v, dict)]


def runtime_file_names(dirs: list[Path], artifact: str, version: str) -> set[str]:
    """File names Gradle metadata gives the runtime variants (AndroidX stores e.g. `ui.aar`)."""
    names = set()
    for d in dirs:
        for module in d.glob(f"{artifact}-{version}.module"):
            try:
                data = json.loads(module.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            for variant in variants_of(data):
                attrs = variant.get("attributes") or {}
                if attrs.get("org.gradle.usage") == "java-runtime" and attrs.get("org.gradle.category", "library") == "library":
                    names.update(str(f.get("name", "")) for f in variant.get("files") or []
                                 if isinstance(f, dict) and str(f.get("name", "")).endswith((".jar", ".aar")))
    return names


def platform_redirects(group: str, artifact: str, version: str, cache: Path, repos: list[Path]) -> list[tuple[str, str, str]]:
    """Kotlin Multiplatform root modules publish no jar; follow their Android/JVM available-at."""
    modules = list((cache / group / artifact / version).glob(f"*/{artifact}-{version}.module"))
    for repo in repos:
        candidate = repo.joinpath(*group.split("."), artifact, version, f"{artifact}-{version}.module")
        if candidate.is_file():
            modules.append(candidate)
    for module in modules:
        try:
            data = json.loads(module.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        ranked = []
        for variant in variants_of(data):
            target = variant.get("available-at")
            attrs = variant.get("attributes") or {}
            if not isinstance(target, dict) or attrs.get("org.gradle.usage") != "java-runtime":
                continue
            rank = {"androidJvm": 0, "jvm": 1}.get(attrs.get("org.jetbrains.kotlin.platform.type"))
            if rank is not None and target.get("module"):
                ranked.append((rank, target.get("group", group), target["module"], target.get("version", version)))
        if ranked:
            _, g, a, v = min(ranked)
            return [(g, a, v)]
    # No Gradle module metadata on disk: try the usual KMP platform artifact names.
    return [(group, f"{artifact}-{suffix}", version) for suffix in ("android", "jvm")]


def metadata_only(group: str, artifact: str, version: str, cache: Path, repos: list[Path]) -> bool:
    """True for BOMs and other modules that publish no jar or aar.

    A module whose metadata names a jar/aar that is not on disk is not metadata-only:
    the build has not downloaded it yet (AboutLibraries resolves POMs only)."""
    dirs = [d for d in (cache / group / artifact / version).glob("*") if d.is_dir()]
    dirs += [r.joinpath(*group.split("."), artifact, version) for r in repos]
    for d in dirs:
        for module in d.glob(f"{artifact}-{version}.module") if d.is_dir() else []:
            try:
                data = json.loads(module.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                return False
            variants = variants_of(data)
            names = [f.get("name", "") for v in variants for f in v.get("files") or [] if isinstance(f, dict)]
            redirects = [v for v in variants if v.get("available-at")
                         and (v.get("attributes") or {}).get("org.gradle.usage") == "java-runtime"]
            return not redirects and not any(n.endswith((".jar", ".aar")) for n in names)
    for d in dirs:
        for pom in d.glob(f"{artifact}-{version}.pom") if d.is_dir() else []:
            try:
                text = pom.read_text(encoding="utf-8", errors="replace")
            except OSError:
                return False
            match = re.search(r"<packaging>\s*([^<\s]+)\s*</packaging>", text)
            return bool(match) and match.group(1) == "pom"
    return False


def entry_base(entry: str) -> str:
    return re.split(r"[/!]", entry)[-1]


def embedded_files(path: Path) -> list[tuple[str, str]]:
    """(entry path, text) of NOTICE/LICENSE/third_party_licenses files in a jar or aar."""
    found = []

    def walk(zf: zipfile.ZipFile, prefix: str) -> None:
        for info in zf.infolist():
            name = info.filename
            base = name.rsplit("/", 1)[-1]
            stem, dot, ext = base.rpartition(".")
            suffix = f".{ext.lower()}" if dot else ""
            if not dot:
                stem = base
            if name.lower().endswith(".jar") and (name == "classes.jar" or name.startswith("libs/")):
                try:
                    walk(zipfile.ZipFile(io.BytesIO(zf.read(info))), f"{prefix}{name}!")
                except zipfile.BadZipFile:
                    pass
                continue
            if info.is_dir() or info.file_size > 4_000_000:
                continue
            google = base in ("third_party_licenses.txt", "third_party_licenses.json")
            if google or (suffix in TEXT_SUFFIXES and (NOTICE_NAME_RE.search(stem) or LICENSE_NAME_RE.search(stem))):
                found.append((prefix + name, zf.read(info).decode("utf-8", "replace")))

    try:
        walk(zipfile.ZipFile(path), "")
    except zipfile.BadZipFile as exc:
        raise InputError(f"{path}: {exc}") from exc
    return found


def google_license_chunks(files: dict[str, str]) -> list[tuple[str, str]]:
    """Split Play services third_party_licenses.txt files by the byte offsets in the .json
    beside them (AAR root or META-INF/third_party_licenses/<group>/<artifact>/)."""
    chunks = []
    for key, txt in sorted(files.items()):
        if not key.endswith("third_party_licenses.txt"):
            continue
        index = files.get(key[: -len(".txt")] + ".json")
        raw = txt.encode("utf-8")
        parts = []
        try:
            for name, span in sorted(json.loads(index).items()) if index else []:
                start, length = int(span.get("start", 0)), int(span.get("length", 0))
                # A missing or zero length means "to the end" (oss-licenses-plugin semantics).
                stop = start + length if length > 0 else len(raw)
                parts.append((name, raw[start:stop].decode("utf-8", "replace")))
        except (ValueError, KeyError, TypeError, AttributeError):
            parts = []
        chunks += parts or [(key, txt)]  # no usable index: require the whole file
    return chunks


def fetch_coordinate(group: str, artifact: str, version: str, sources: list[str], dest: Path) -> None:
    """Download a coordinate's metadata and runtime files into dest, laid out as a Maven repository.

    CI Gradle caches (e.g. setup-gradle) may restore the dependency metadata
    without the jars and aars the build no longer needed to download."""
    rel = "/".join([*group.split("."), artifact, version])
    for base in sources:
        found = False
        for name in (f"{artifact}-{version}.module", f"{artifact}-{version}.pom",
                     f"{artifact}-{version}.aar", f"{artifact}-{version}.jar"):
            target = dest.joinpath(rel, name)
            if target.is_file():
                found = True
                continue
            try:
                with urllib.request.urlopen(f"{base.rstrip('/')}/{rel}/{name}", timeout=60) as response:
                    data = response.read()
            except urllib.error.HTTPError as error:
                if error.code == 404:
                    continue
                raise InputError(f"{base}: {rel}/{name}: HTTP {error.code}") from error
            except urllib.error.URLError as error:
                raise InputError(f"{base}: {rel}/{name}: {error.reason}") from error
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            found = True
        if found:
            return


def resolve_files(group: str, artifact: str, version: str, cache: Path, repos: list[Path]) -> tuple[list[Path], bool]:
    """Runtime files of a coordinate, following Kotlin Multiplatform redirects."""
    files, known = artifact_files(group, artifact, version, cache, repos)
    if not files:
        for g, a, v in platform_redirects(group, artifact, version, cache, repos):
            files += artifact_files(g, a, v, cache, repos)[0]
            if files:
                break
    return files, known


def cmd_scan(args) -> int:
    cfg = load_config(args.config)
    defs, _ = load_source(args.input, args.definitions_entry)
    if defs is None:
        raise InputError(f"{args.input}: no definitions to take coordinates from")
    cache = gradle_cache(args.gradle_home)
    repos = [Path(r) for r in args.maven_repo]
    # Files missing from the local caches are downloaded here when --fetch-from is given.
    fetched_dir = tempfile.TemporaryDirectory(prefix="android-notices-")
    fetched = Path(fetched_dir.name)
    if args.fetch_from:
        repos.append(fetched)
    extra = norm("\n".join(read_text(t) for t in args.text))
    errors, notes = [], [f"coordinates: {defs['origin']} ({len(defs['libraries'])} libraries)"]
    scanned = 0
    for lib in sorted(defs["libraries"], key=lambda item: item["uniqueId"]):
        ident, version = lib["uniqueId"], str(lib.get("artifactVersion") or "")
        if lib.get("tag") == "bundled" or ident.count(":") != 1 or not version:
            continue  # hand-maintained entry, nothing to resolve
        group, artifact = ident.split(":")
        files, known = resolve_files(group, artifact, version, cache, repos)
        if not files and args.fetch_from:
            fetch_coordinate(group, artifact, version, args.fetch_from, fetched)
            for g, a, v in platform_redirects(group, artifact, version, cache, repos):
                fetch_coordinate(g, a, v, args.fetch_from, fetched)
            files, known = resolve_files(group, artifact, version, cache, repos)
        if not files:
            if known and metadata_only(group, artifact, version, cache, repos):
                continue  # BOM, platform or other module without code
            if not waived(cfg, "missing-artifact", ident):
                errors.append(f"{ident}:{version}: artifact not found in {cache} or --maven-repo "
                              "(build first, or waive missing-artifact)")
            continue
        scanned += 1
        own = norm("\n".join((license_of(defs, k).get("content") or "") for k in lib.get("licenses", [])))
        own += " " + norm(lib.get("description") or "")
        fams = sorted({family(license_of(defs, k), k) for k in lib.get("licenses", [])} & COPYRIGHT_FAMILIES)
        for path in files:
            embedded = dict(embedded_files(path))
            for entry, text in sorted(embedded.items()):
                stem = entry_base(entry).rsplit(".", 1)[0]
                if not norm(text) or norm(text) in own or norm(text) in extra:
                    continue
                if NOTICE_NAME_RE.search(stem):
                    if not waived(cfg, "notice", ident):
                        errors.append(f"{ident}:{version}: {path.name}!{entry} is not reproduced in the shipped "
                                      "notices (Apache-2.0 4(d)); get it with `scan --extract DIR` and add it "
                                      f"with `stub --notice FILE --id {ident}`")
                elif fams and LICENSE_NAME_RE.search(stem) and not stem.startswith("third_party_licenses") \
                        and has_copyright(text) and not has_placeholder(text) \
                        and not GENERIC_HEAD_RE.search(norm(text)[:300]) and not waived(cfg, "license-file", ident):
                    # The artifact's own MIT/BSD-style file is the text to ship; a different one
                    # usually means `stub --text` was pointed at the wrong upstream file.
                    errors.append(f"{ident}:{version}: {path.name}!{entry} ({'/'.join(fams)} text with a copyright "
                                  "line) is not reproduced in the shipped notices; get it with `scan --extract DIR` "
                                  f"and add it with `stub --text FILE --id {ident} --spdx {fams[0]}`, or waive "
                                  "license-file with the reason the shipped text differs")
            for name, chunk in google_license_chunks(embedded):
                if norm(chunk) and norm(chunk) not in own and norm(chunk) not in extra \
                        and not waived(cfg, "notice", ident):
                    errors.append(f"{ident}:{version}: embedded third_party_licenses entry '{name}' "
                                  "is not reproduced in the shipped notices")
            for entry, text in sorted(embedded.items()):
                if args.verbose:
                    notes.append(f"{ident}:{version}: {path.name}!{entry}")
                if args.extract:
                    # Upstream texts to feed `stub --text/--notice` after review.
                    parts = [part for part in re.split(r"[/!]", entry) if part not in ("", ".", "..")]
                    target = Path(args.extract, stub_name(f"{ident}-{version}"), *parts)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(text, encoding="utf-8")
    notes.append(f"scanned {scanned} artifacts")
    return report(errors, notes, args.quiet)


