def report(errors: list[str], notes: list[str], quiet: bool) -> int:
    if not quiet:
        for note in notes:
            print(f"note: {note}")
    for error in errors:
        print(f"error: {error}", file=sys.stderr)
    if errors:
        print(f"{len(errors)} problem(s)", file=sys.stderr)
        return 1
    print("ok")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", action="version", version=f"%(prog)s {TOOL_VERSION}")
    sub = parser.add_subparsers(dest="command", required=True)

    def common(p):
        p.add_argument("input", help="APK, AAB, aboutlibraries.json or Licensee artifacts.json")
        p.add_argument("--config", help="TOML overrides (claims, waivers, required entries)")
        p.add_argument("--definitions-entry", help="archive path of the definitions, if not auto-detected")
        p.add_argument("-q", "--quiet", action="store_true")

    p = sub.add_parser("check", help="verify notices inside a built APK/AAB (or a definitions JSON)")
    common(p)
    p.add_argument("--require", action="append", default=[], help="uniqueId that must be listed")
    p.add_argument("--require-entry", action="append", default=[], help="archive entry that must be non-empty")
    p.add_argument("--require-text", action="append", default=[], help="ENTRY=TEXT the entry must contain")
    p.add_argument("--text-entry", action="append", default=[],
                   help="extra notice file inside the archive searched by requires_text")
    p.add_argument("--no-definitions", action="store_true", help="the app ships notices in another format")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("scan", help="find NOTICE files in resolved artifacts the notices miss")
    common(p)
    p.add_argument("--gradle-home", help="default: $GRADLE_USER_HOME or ~/.gradle")
    p.add_argument("--maven-repo", action="append", default=[], help="extra local Maven repository")
    p.add_argument("--fetch-from", action="append", default=[], metavar="URL",
                   help="remote Maven repository to download artifacts missing locally from, repeatable "
                        "(e.g. https://dl.google.com/dl/android/maven2, https://repo.maven.apache.org/maven2)")
    p.add_argument("--text", action="append", default=[], help="extra notices file that counts as shipped")
    p.add_argument("-v", "--verbose", action="store_true", help="list every embedded license file")
    p.add_argument("--extract", metavar="DIR", help="write every embedded LICENSE/NOTICE file below DIR")
    p.set_defaults(func=cmd_scan)

    p = sub.add_parser("render", help="write a plain-text Third-Party-Notices.txt")
    p.add_argument("input")
    p.add_argument("-o", "--output", required=True)
    p.add_argument("--header", help="text placed before the entries")
    p.add_argument("--definitions-entry")
    p.set_defaults(func=cmd_render)

    p = sub.add_parser("stub", help="write config/licenses (+ config/libraries) JSON for one component")
    p.add_argument("--config-dir", required=True, help="AboutLibraries configPath, e.g. app/config")
    p.add_argument("--id", required=True, help="uniqueId: group:artifact, or <project>:<name> if not Maven")
    p.add_argument("--spdx", required=True, help="SPDX id of the license family, e.g. MIT, Apache-2.0")
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--text", help="upstream license file with the real copyright line")
    src.add_argument("--notice", help="upstream NOTICE file (Apache-2.0 4(d))")
    p.add_argument("--reason", required=True, help="why and where the text comes from (stored as _comment)")
    p.add_argument("--key", help="license hash, default <spdx>-<artifact>[-NOTICE]")
    p.add_argument("--name", help="display name (required with --bundled)")
    p.add_argument("--url", help="upstream URL of the text at the shipped version")
    p.add_argument("--bundled", action="store_true", help="non-Maven content: write a full library entry")
    p.add_argument("--version")
    p.add_argument("--website")
    p.add_argument("--description", help="what ships where; source pointer for MPL/LGPL/GPL; "
                   "modified or not for CC BY")
    p.add_argument("--developer", action="append", default=[], help="creator to credit (CC BY), repeatable")
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=cmd_stub)

    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except InputError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
