#!/usr/bin/env python3
# SPDX-License-Identifier: Unlicense
"""Check, scan and render the third-party notices an Android app ships.

The notices are AboutLibraries library definitions (res/raw/aboutlibraries.json,
generated by the com.mikepenz.aboutlibraries.plugin Gradle plugin from the
resolved dependency graph plus the hand-maintained config/libraries and
config/licenses entries). Python 3.11+ standard library only.

  check  APK|AAB|JSON  CI gate on the built artifact: definitions present, every
                       component has license text, MIT/BSD-style licenses carry
                       the component's own copyright line instead of a template,
                       CC BY entries name creator, source and modification status,
                       LGPL-3.0 ships with the GPL-3.0 text, and every native
                       library, font, model, web asset or sound in the APK is
                       claimed by a notice entry.
  scan   APK|AAB|JSON  open every resolved Maven artifact (Gradle cache or local
                       Maven repositories) and fail when one embeds a NOTICE file,
                       a Google-style third_party_licenses list, or (for MIT/BSD-
                       style components) a license file with a copyright line,
                       whose text the shipped notices do not reproduce.
  render APK|AAB|JSON  write a sorted plain-text Third-Party-Notices.txt.
  stub                 write a config/licenses (and config/libraries) JSON entry
                       from an upstream license or NOTICE file.

Overrides live in a TOML file passed with --config; every entry needs a reason.
Exit status: 0 clean, 1 findings, 2 usage or input errors.
"""

