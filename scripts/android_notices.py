def check_definitions(defs: dict, cfg: dict, errors: list[str]) -> None:
    libraries = defs["libraries"]
    if not libraries:
        errors.append(f"{defs['origin']}: no libraries listed")
        return
    for lib in libraries:
        ident = lib.get("uniqueId") or lib.get("name") or "?"
        keys = list(lib.get("licenses") or [])
        if not keys:
            if not waived(cfg, "license", ident):
                errors.append(f"{ident}: no license (add config/libraries/{stub_name(ident)}.json, see recipe)")
            continue
        if defs["format"] != "aboutlibraries":
            continue
        by_family: dict[str, list[tuple[str, str]]] = {}
        for key in keys:
            lic = license_of(defs, key)
            content = (lic.get("content") or "").strip()
            if not content:
                if not waived(cfg, "content", ident):
                    errors.append(f"{ident}: license '{key}' has no text "
                                  f"(add config/licenses JSON with \"hash\": \"{key}\")")
                continue
            by_family.setdefault(family(lic, key), []).append((key, content))
        for fam, texts in sorted(by_family.items()):
            if all(has_placeholder(t) for _, t in texts):
                if not waived(cfg, "template", ident):
                    errors.append(f"{ident}: {fam} text is a template ({texts[0][0]} has placeholders); "
                                  f"add the component's own license text (stub --spdx {fam})")
                continue
            if fam in COPYRIGHT_FAMILIES and not any(has_copyright(t) and not has_placeholder(t) for _, t in texts):
                if not waived(cfg, "copyright", ident):
                    errors.append(f"{ident}: no {fam} text with a copyright line "
                                  f"({', '.join(k for k, _ in texts)}); add the component's own license text")
        # CC BY 4.0 3(a)(1): identify the creator, link the material, say whether it was modified.
        if any(fam.upper().startswith("CC-BY") for fam in by_family) and not waived(cfg, "attribution", ident):
            creators = [d.get("name") for d in lib.get("developers") or [] if isinstance(d, dict) and d.get("name")]
            if isinstance(lib.get("organization"), dict) and lib["organization"].get("name"):
                creators.append(lib["organization"]["name"])
            missing = [what for what, ok in (
                ("creator (developers or organization)", creators),
                ("source URL (website)", lib.get("website")),
                ("modification status in the description (e.g. \"Unmodified.\")",
                 re.search(r"modifi", str(lib.get("description") or ""), re.IGNORECASE)),
            ) if not ok]
            if missing:
                errors.append(f"{ident}: CC BY attribution lacks {', '.join(missing)}")
        if any(fam.upper().startswith("LGPL-3.0") for fam in by_family) and not waived(cfg, "gpl-text", ident):
            if not any(GPL3_TEXT_RE.search(lic.get("content") or "") for lic in defs["licenses"].values()):
                errors.append(f"{ident}: LGPL-3.0 needs the GPL-3.0 text shipped as well (LGPL-3.0 4(b))")


def is_notice_file(name: str) -> bool:
    """Shipped notice files are not content that needs a claim."""
    base = entry_base(name)
    stem, dot, ext = base.rpartition(".")
    stem, suffix = (stem, f".{ext.lower()}") if dot else (base, "")
    named = bool(NOTICE_NAME_RE.search(stem) or LICENSE_NAME_RE.search(stem))
    return name.startswith("assets/licenses/") or (named and suffix in TEXT_SUFFIXES)


def all_texts(defs: dict | None, archive: Archive | None, text_entries: list[str]) -> str:
    parts = []
    if defs:
        parts += [lic.get("content") or "" for lic in defs["licenses"].values()]
        parts += [lib.get("description") or "" for lib in defs["libraries"]]
    if archive:
        for name in text_entries:
            if archive.size(name) > 0:
                parts.append(archive.read(name).decode("utf-8", "replace"))
    return norm("\n".join(parts))


def check_archive(archive: Archive, defs: dict | None, cfg: dict, args, errors: list[str], notes: list[str]) -> None:
    ids = {lib.get("uniqueId") for lib in defs["libraries"]} if defs else set()
    texts = all_texts(defs, archive, args.text_entry)
    watch = [glob_re(p) for p in DEFAULT_WATCH + list(cfg["watch"])]
    claims = [(c, [glob_re(p) for p in c["paths"]]) for c in cfg["claim"]]
    used = set()
    for name in sorted(archive.entries):
        if not any(w.match(name) for w in watch) or is_notice_file(name):
            continue
        matched = [i for i, (_, regs) in enumerate(claims) if any(r.match(name) for r in regs)]
        if not matched:
            errors.append(f"{name}: unclaimed third-party content; add a [[claim]] to the config")
        used.update(matched)
    for i in sorted(used):
        claim = claims[i][0]
        label = f"claim {claim['paths']}"
        for ident in claim.get("requires", []):
            if ident not in ids:
                errors.append(f"{label}: no notice entry '{ident}' in the definitions")
        for marker in claim.get("requires_text", []):
            if norm(marker) not in texts:
                errors.append(f"{label}: no shipped notice contains '{marker}'")
        for entry in claim.get("requires_entries", []):
            if archive.size(entry) <= 0:
                errors.append(f"{label}: {entry} missing or empty in the artifact")
    for i, (claim, _) in enumerate(claims):
        if i not in used:
            notes.append(f"claim {claim['paths']} matched nothing in this artifact")
    # Core library desugaring dexes j$.* classes from desugar_jdk_libs, which no
    # runtime classpath lists.
    dexes = [n for n in archive.entries if re.fullmatch(r"(?:dex/)?classes\d*\.dex", n)]
    if any(b"Lj$/" in archive.read(n) for n in dexes):
        if not any(i.startswith("com.android.tools:desugar_jdk_libs") for i in ids) \
                and not waived(cfg, "desugar", "desugar_jdk_libs"):
            errors.append("dex contains desugared j$ classes but no com.android.tools:desugar_jdk_libs* entry")


def cmd_check(args) -> int:
    cfg = load_config(args.config)
    errors, notes = [], []
    defs, archive = load_source(args.input, args.definitions_entry)
    if defs is None and not args.no_definitions:
        errors.append(f"{args.input}: no AboutLibraries definitions (res/raw/aboutlibraries.json or a "
                      "shortened res/*.json); is the AboutLibraries Android plugin applied?")
    if defs is None and (cfg["require"] or args.require):
        errors.append("required notice entries given, but the artifact has no definitions")
    if defs is not None:
        notes.append(f"definitions: {defs['origin']} ({defs['format']}, {len(defs['libraries'])} libraries)")
        if defs["format"] == "licensee":
            notes.append("Licensee list: license texts are checked only through --require-text/--text-entry")
        check_definitions(defs, cfg, errors)
        ids = {lib.get("uniqueId") for lib in defs["libraries"]}
        for ident in list(cfg["require"]) + args.require:
            if ident not in ids:
                errors.append(f"required notice entry '{ident}' is missing")
    if archive is not None:
        for entry in args.require_entry:
            if archive.size(entry) <= 0:
                errors.append(f"{entry}: missing or empty in {args.input}")
        for spec in args.require_text:
            entry, sep, marker = spec.partition("=")
            if not sep or not marker.strip():
                raise InputError(f"--require-text needs ENTRY=TEXT, got {spec!r}")
            if archive.size(entry) <= 0:
                errors.append(f"{entry}: missing or empty in {args.input}")
            elif norm(marker) not in norm(archive.read(entry).decode("utf-8", "replace")):
                errors.append(f"{entry}: does not contain '{marker}'")
        check_archive(archive, defs, cfg, args, errors, notes)
    elif args.require_entry or args.require_text:
        raise InputError("--require-entry/--require-text need an APK or AAB")
    return report(errors, notes, args.quiet)


