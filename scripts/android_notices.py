def cmd_render(args) -> int:
    defs, _ = load_source(args.input, args.definitions_entry)
    if defs is None or defs["format"] != "aboutlibraries":
        raise InputError(f"{args.input}: no AboutLibraries definitions to render")
    rule = "=" * 72
    out = [args.header.rstrip() + "\n"] if args.header else []
    for lib in sorted(defs["libraries"], key=lambda l: (str(l.get("name") or "").lower(), l["uniqueId"])):
        keys = list(lib.get("licenses") or [])
        texts = [(k, license_of(defs, k)) for k in keys]
        missing = [k for k, lic in texts if not (lic.get("content") or "").strip()]
        if not keys or missing:
            raise InputError(f"{lib.get('uniqueId')}: no license text for {missing or 'any license'}; run check")
        source = lib.get("website") or (lib.get("scm") or {}).get("url") or ""
        head = [rule, f"{lib.get('name') or lib.get('uniqueId')} {lib.get('artifactVersion') or ''}".rstrip(),
                lib.get("uniqueId", ""), " AND ".join(sorted({family(l, k) for k, l in texts}))]
        if source:
            head.append(source)
        attribution = any(family(l, k).upper().startswith("CC-BY") for k, l in texts)
        creators = [d.get("name") for d in lib.get("developers") or [] if isinstance(d, dict) and d.get("name")]
        if attribution and creators:
            head.append("By " + ", ".join(creators))
        if lib.get("description") and (lib.get("tag") == "bundled" or attribution):
            head.append(lib["description"])
        out.append("\n".join(head) + "\n")
        for key, lic in texts:
            out.append(f"\n{lic.get('name') or key}\n\n{lic['content'].strip()}\n")
        out.append("\n")
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text("".join(out), encoding="utf-8")
    return 0


# --------------------------------------------------------------------------- stub

def stub_name(ident: str) -> str:
    """File name for a uniqueId: group:artifact -> group__artifact."""
    return re.sub(r"[^A-Za-z0-9._-]+", "__", ident)


def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9.+-]+", "-", text).strip("-")


def write_json(path: Path, data: dict, force: bool) -> None:
    if path.exists() and not force:
        raise InputError(f"{path} exists (use --force to replace)")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path}")


def read_text(path: str) -> str:
    try:
        return Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        raise InputError(f"cannot read {path}: {exc}") from exc


def cmd_stub(args) -> int:
    config = Path(args.config_dir)
    if args.bundled and not (args.name and args.version and args.website):
        raise InputError("--bundled needs --name, --version and --website")
    source = args.notice or args.text
    content = read_text(source).strip() + "\n"
    if args.notice:
        content = f"NOTICE file of {args.name or args.id}:\n\n{content}"
    elif has_placeholder(content):
        raise InputError(f"{source}: still a template (placeholders found); use the upstream text")
    key = args.key or slug(f"{args.spdx}-{args.id.rsplit(':', 1)[-1]}" + ("-NOTICE" if args.notice else ""))
    lic = {
        "_comment": args.reason,
        "hash": key,
        "spdxId": args.spdx,
        "name": f"{args.name or args.id} NOTICE" if args.notice else f"{args.spdx} ({args.name or args.id})",
        "url": args.url or "",
        "content": content,
    }
    write_json(config / "licenses" / f"{slug(key)}.json", lic, args.force)
    library = {"_comment": args.reason, "uniqueId": args.id, "licenses": [key]}
    developers = [{"name": name} for name in args.developer]
    if args.bundled:
        library.update({"name": args.name, "artifactVersion": args.version, "website": args.website,
                        "description": args.description or "", "developers": developers, "tag": "bundled"})
    else:
        if args.description:
            library["description"] = args.description
        if developers:
            library["developers"] = developers  # the plugin adds these to the POM's developers
    lib_path = config / "libraries" / f"{stub_name(args.id)}.json"
    if lib_path.exists():
        # Add the key to the existing entry; --force also replaces its other fields.
        try:
            existing = json.loads(lib_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise InputError(f"{lib_path}: {exc}") from exc
        keys = set(existing.get("licenses") or []) | {key}
        comment = "; ".join(dict.fromkeys(c for c in (existing.get("_comment"), args.reason) if c))
        merged = {**existing, **(library if args.force else {}), "licenses": sorted(keys), "_comment": comment}
        if args.description:
            merged["description"] = args.description
        known = [d for d in merged.get("developers") or [] if isinstance(d, dict)]
        extra = [d for d in developers if d not in known]
        if extra:
            merged["developers"] = known + extra
        if merged != existing:
            write_json(lib_path, merged, True)
    else:
        write_json(lib_path, library, False)
    return 0


