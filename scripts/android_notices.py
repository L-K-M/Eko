def load_config(path: str | None) -> dict:
    cfg = {"watch": [], "claim": [], "waive": [], "require": []}
    if not path:
        return cfg
    if tomllib is None:
        raise InputError("--config needs Python 3.11+ (tomllib)")
    try:
        data = tomllib.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise InputError(f"cannot read config {path}: {exc}") from exc
    unknown = set(data) - set(cfg)
    if unknown:
        raise InputError(f"{path}: unknown top-level keys {sorted(unknown)}")
    cfg.update(data)
    for key in ("watch", "require"):
        if not (isinstance(cfg[key], list) and all(isinstance(v, str) for v in cfg[key])):
            raise InputError(f"{path}: `{key}` must be a list of strings")
    for key in ("claim", "waive"):
        if not (isinstance(cfg[key], list) and all(isinstance(v, dict) for v in cfg[key])):
            raise InputError(f"{path}: use [[{key}]] tables")
    for i, claim in enumerate(cfg["claim"]):
        where = f"{path}: claim #{i + 1}"
        extra = set(claim) - {"paths", "requires", "requires_text", "requires_entries", "own", "reason"}
        if extra:
            raise InputError(f"{where}: unknown keys {sorted(extra)}")
        if not claim.get("paths") or not claim.get("reason"):
            raise InputError(f"{where}: needs `paths` and `reason`")
        for key in ("paths", "requires", "requires_text", "requires_entries"):
            value = claim.get(key, [])
            if not (isinstance(value, list) and all(isinstance(v, str) and v for v in value)):
                raise InputError(f"{where}: `{key}` must be a list of non-empty strings")
        if not (claim.get("own") or claim.get("requires") or claim.get("requires_text") or claim.get("requires_entries")):
            raise InputError(f"{where}: needs `requires`, `requires_text`, `requires_entries` or `own = true`")
    for i, waiver in enumerate(cfg["waive"]):
        where = f"{path}: waive #{i + 1}"
        extra = set(waiver) - {"id", "check", "reason"}
        if extra:
            raise InputError(f"{where}: unknown keys {sorted(extra)}")
        if not waiver.get("id") or not waiver.get("reason") or waiver.get("check") not in WAIVABLE:
            raise InputError(f"{where}: needs `id`, `reason` and `check` in {sorted(WAIVABLE)}")
    return cfg


def waived(cfg: dict, check: str, ident: str) -> bool:
    return any(w["check"] == check and fnmatch.fnmatchcase(ident, w["id"]) for w in cfg["waive"])


def glob_re(pattern: str) -> re.Pattern:
    """`**/` matches any directory depth, `*` and `?` stay within one path segment."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out) + r"\Z")


